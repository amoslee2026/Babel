#!/usr/bin/env python3
"""Generate executable SystemVerilog testcases from structured test points.

Consumes tb_manifest.json (ports/clocks) written by bb-generate-testbench and
owns tc_<module>.sv, test_registry.json, test_cases.md, run_tests.sh.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime, timezone, timedelta
from pathlib import Path

CST = timezone(timedelta(hours=8))
HEADER = "// Generated by bb-generate-testcases — rerun the skill instead of editing.\n"
SELECTOR_RE = re.compile(r"(mode|sel|prec|format|enable|start|valid|op)", re.I)


def rel(p: Path, root: Path) -> str:
    try:
        return str(p.relative_to(root))
    except ValueError:
        return str(p)


def task_name(tp_id: str) -> str:
    return "tc_" + re.sub(r"[^A-Za-z0-9]", "_", tp_id)


def is_clock(p: dict) -> bool:
    return bool(re.search(r"clk|clock", p["name"], re.I))


def is_reset(p: dict) -> bool:
    return p["dir"] == "input" and bool(re.match(r"^rst", p["name"], re.I))


def numeric_width(p: dict) -> int | None:
    w = p.get("width")
    return w if isinstance(w, int) else None


def narrow_inputs(ports: list[dict]) -> list[dict]:
    return [
        p for p in ports
        if p["dir"] == "input" and not is_clock(p) and not is_reset(p)
        and numeric_width(p) is not None and numeric_width(p) <= 16
    ]


def randomize_line(p: dict) -> str:
    w = numeric_width(p)
    return f"  {p.get('signal', p['name'])} = {w}'($urandom);"


def wait_line(clk: str | None, cycles: int) -> str:
    if clk:
        return f"  repeat ({cycles}) @(posedge {clk});"
    return f"  #{cycles * 10};"


def gen_task(idx: int, tp: dict, ports: list[dict], clk: str | None) -> list[str]:
    cat = tp.get("category", "functional")
    name = task_name(tp["id"])
    L = [
        f"// {tp['id']} [{cat}/{tp.get('priority','MEDIUM')}] {tp.get('title','')}",
        f"task automatic {name}();",
        f"  int idx = {idx};",
        "  drive_defaults();",
        "  apply_reset();",
    ]

    if cat in ("functional", "cdc"):
        for p in narrow_inputs(ports):
            L.append(randomize_line(p))
        if cat == "cdc":
            L += [wait_line(clk, 16), "  sb_check(idx);"]
        else:
            L += [wait_line(clk, 8), "  sb_check(idx);"]
    elif cat == "branch":
        sels = [p for p in narrow_inputs(ports) if SELECTOR_RE.search(p["name"])]
        targets = sels or narrow_inputs(ports)
        for p in targets:
            L.append(randomize_line(p))
        L += [wait_line(clk, 8), "  sb_check(idx);"]
    elif cat == "boundary":
        wide = [
            p for p in ports
            if p["dir"] == "input" and not is_clock(p) and not is_reset(p)
            and numeric_width(p) is not None
        ]
        if wide:
            p = max(wide, key=lambda q: numeric_width(q) or 1)
            L += [
                f"  {p.get('signal', p['name'])} = '1;",
                wait_line(clk, 4),
                "  sb_check(idx);",
                f"  {p.get('signal', p['name'])} = '0;",
                wait_line(clk, 4),
                "  sb_check(idx);",
            ]
        else:
            L += [wait_line(clk, 4), "  sb_check(idx);"]
    else:  # reset / unknown categories
        L += [wait_line(clk, 2), "  sb_check(idx);"]

    L += ["endtask", ""]
    return L


def gen_tc_file(module: str, tps: list[dict], ports: list[dict], clocks: dict) -> str:
    clk = next(iter(clocks), None) if clocks else None
    L = [HEADER, f"// module: {module} | testcases: {len(tps)}", ""]
    for i, tp in enumerate(tps):
        L += gen_task(i, tp, ports, clk)
    L += ["task automatic run_tc(string id);", "  case (id)"]
    for tp in tps:
        L.append(f'    "{tp["id"]}": {task_name(tp["id"])}();')
    L += ['    default: $display("[TB] unknown test id: %s", id);',
          "  endcase", "endtask", "",
          "task automatic run_all();", "  string sel;",
          '  if ($value$plusargs("TC=%s", sel)) begin',
          "    run_tc(sel);",
          "  end else begin"]
    for tp in tps:
        L.append(f"    {task_name(tp['id'])}();")
    L += ["  end", "endtask", ""]
    return "\n".join(L)


def run_lint(modules: list[str], tb_dir: Path, root: Path) -> tuple[bool, list[str]]:
    errors: list[str] = []
    for m in modules:
        cmd = ["verilator", "--lint-only", "-sv", "--timing", "-Wno-fatal",
               "--top-module", f"tb_{m}", "-f", str(tb_dir / "rtl.f"),
               str(tb_dir / f"tb_{m}.sv")]
        try:
            res = subprocess.run(cmd, capture_output=True, text=True, timeout=600, cwd=str(root))
        except (OSError, subprocess.TimeoutExpired) as exc:
            return False, [f"{m}: lint invocation failed: {exc}"]
        if res.returncode != 0:
            errs = [ln for ln in (res.stdout + res.stderr).splitlines() if "%Error" in ln]
            errors += (errs or [f"{m}: verilator exit {res.returncode}"])[:20]
    return not errors, errors[:20]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--design-name", required=True)
    ap.add_argument("--test-points", required=True)
    ap.add_argument("--tb-dir", required=True)
    ap.add_argument("--modules")
    ap.add_argument("--no-lint", action="store_true")
    args = ap.parse_args()

    root = Path.cwd()
    tp_doc = json.loads(Path(args.test_points).read_text(encoding="utf-8"))
    tb_dir = Path(args.tb_dir)
    manifest_path = tb_dir / "tb_manifest.json"
    if not manifest_path.is_file():
        print(json.dumps({"valid": False, "error": f"missing {manifest_path}"}, ensure_ascii=False))
        return 1
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    by_module: dict[str, list[dict]] = {}
    for tp in tp_doc.get("points", []):
        by_module.setdefault(tp["module"], []).append(tp)

    available = set(manifest.get("modules") or [])
    wanted = [m.strip() for m in args.modules.split(",")] if args.modules else sorted(by_module)
    missing = [m for m in wanted if m not in available]

    registry: list[dict] = []
    tc_files: list[str] = []
    generated: list[str] = []
    for mod in wanted:
        if mod not in available:
            continue
        tps = by_module.get(mod) or []
        ports = manifest.get("ports", {}).get(mod) or []
        clocks = manifest.get("clocks", {}).get(mod) or {}
        tc = tb_dir / f"tc_{mod}.sv"
        tc.write_text(gen_tc_file(mod, tps, ports, clocks), encoding="utf-8")
        tc_files.append(rel(tc, root))
        generated.append(mod)
        for i, tp in enumerate(tps):
            registry.append({
                "id": tp["id"],
                "source_id": tp.get("source_id", "derived"),
                "module": mod,
                "task": task_name(tp["id"]),
                "priority": tp.get("priority", "MEDIUM"),
                "category": tp.get("category", "functional"),
                "title": tp.get("title", ""),
                "coverage_bin": f"cg_{mod}.cp_tp.tp_{i}",
                "check_kind": "non_x_only",
                "stimulus": tp.get("stimulus", ""),
                "check": tp.get("check", ""),
            })

    verif_dir = Path("designs") / args.design_name / "verif"
    verif_dir.mkdir(parents=True, exist_ok=True)
    reg_path = verif_dir / "test_registry.json"
    prev_cases: list[dict] = []
    if reg_path.is_file():
        try:
            prev_cases = json.loads(reg_path.read_text(encoding="utf-8")).get("cases", [])
        except json.JSONDecodeError:
            prev_cases = []
    kept = [c for c in prev_cases if c.get("module") not in set(generated)]
    all_cases = sorted(kept + registry, key=lambda c: c["id"])
    reg_doc = {
        "design_name": args.design_name,
        "generated": datetime.now(CST).isoformat(timespec="seconds"),
        "testcases": len(all_cases),
        "missing_modules": missing,
        "cases": all_cases,
    }
    reg_path.write_text(json.dumps(reg_doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    md_lines = [
        f"# Test Cases — {args.design_name}",
        "",
        f"> {len(all_cases)} 个 testcase ｜ 生成时间 {reg_doc['generated']}",
        "",
        "| TP | Module | Task | Category | Priority | Coverage Bin | Run |",
        "|----|--------|------|----------|----------|--------------|-----|",
    ]
    for c in all_cases:
        md_lines.append(
            f"| {c['id']} | {c['module']} | `{c['task']}` | {c['category']} | {c['priority']} | "
            f"`{c['coverage_bin']}` | `run_tests.sh {c['module']} {c['id']}` |"
        )
    md_path = verif_dir / "test_cases.md"
    md_path.write_text("\n".join(md_lines) + "\n", encoding="utf-8")

    runner = tb_dir / "run_tests.sh"
    runner.write_text(
        "\n".join(
            [
                "#!/usr/bin/env bash",
                "set -uo pipefail",
                'cd "$(git rev-parse --show-toplevel)"',
                f'GEN="{rel(tb_dir, root)}"',
                'MOD="${1:-}"',
                'TC="${2:-}"',
                'if [[ -z "$MOD" ]]; then MODULES=' + '"' + " ".join(generated) + '"' + '; else MODULES="$MOD"; fi',
                "rc=0",
                "for m in $MODULES; do",
                '  obj=/tmp/babel-sim/$m',
                '  mkdir -p "$obj"',
                '  verilator --binary -j 0 -sv --timing -Wno-fatal --top-module "tb_$m" \\',
                '    -f "$GEN/rtl.f" "$GEN/tb_$m.sv" --Mdir "$obj" -o "sim_$m" --quiet || { echo "[build] $m FAILED"; rc=1; continue; }',
                '  if [[ -n "$TC" ]]; then',
                '    "$obj/sim_$m" +TC="$TC" || rc=1',
                "  else",
                '    "$obj/sim_$m" || rc=1',
                "  fi",
                "done",
                "exit $rc",
                "",
            ]
        ),
        encoding="utf-8",
    )
    runner.chmod(0o755)

    lint_clean, lint_errors = True, []
    if generated and not args.no_lint:
        lint_clean, lint_errors = run_lint(generated, tb_dir, root)

    valid = bool(registry) and lint_clean
    print(json.dumps({
        "artifact_path": str(reg_path),
        "tc_files": tc_files,
        "testcases": len(all_cases),
        "markdown_path": str(md_path),
        "runner": str(runner),
        "missing_modules": missing,
        "lint_clean": lint_clean,
        "lint_errors": lint_errors,
        "valid": valid,
        "error": None if valid else (
            "; ".join(lint_errors[:3]) if lint_errors else "no testcases generated"
        ),
    }, ensure_ascii=False))
    return 0 if valid else 1


if __name__ == "__main__":
    sys.exit(main())
